// Package issue builds a ticket draft (a Jira-style summary line, a markdown
// description and labels) from a finding. It is PURE: it never talks to Jira
// or to any network and never touches files; the AI client hands the draft to
// whichever ticketing MCP server the user runs. A test asserts with
// "go list -deps" that the package imports no net, net/http or os/exec.
//
// Every free-text field is Sanitize'd, URL credentials are scrubbed, fields
// that look like a Secret manifest are replaced whole, each line that looks
// like a credential is masked, and markdown/Jira control sequences are
// neutralised. Quotes go inside a fenced block whose fence is longer than any
// backtick run in the quote, so a quote cannot break out of it.
package issue

import (
	"fmt"
	"regexp"
	"strings"
	"unicode/utf8"

	"github.com/astawiany/k8s-mcp/internal/flux"
	"github.com/astawiany/k8s-mcp/internal/redact"
	"github.com/astawiany/k8s-mcp/internal/untrusted"
)

// Limits on the input.
const (
	MaxTitle       = 120
	MaxSummaryLine = 120
	MaxSummary     = 1000
	MaxEvidence    = 10
	MaxQuote       = 300
	MaxNext        = 10
	MaxNextLen     = 300
	maxRef         = 200
	maxField       = 200
	maxLabel       = 63
)

// SecretReplacement replaces a field that looks like a Secret manifest.
const SecretReplacement = "[redacted: looks like a Secret manifest]"

// Evidence is one piece of evidence: a reference and an optional quote.
type Evidence struct {
	Ref   string `json:"ref"`
	Quote string `json:"quote,omitempty"`
}

// In is the finding to draft a ticket for.
type In struct {
	Title         string
	Severity      string
	Cluster       string
	Namespace     string
	Object        string
	Summary       string
	Evidence      []Evidence
	SuggestedNext []string
}

// Out is the draft.
type Out struct {
	Summary         string   `json:"summary"`
	Description     string   `json:"description"`
	Labels          []string `json:"labels"`
	Warnings        []string `json:"warnings"`
	DroppedEvidence int      `json:"droppedEvidence,omitempty"`
	DroppedNext     int      `json:"droppedSuggestedNext,omitempty"`
}

var impact = map[string]string{
	"low":      "Low impact: a minor issue or improvement with no known effect on users or availability.",
	"medium":   "Medium impact: degraded behaviour or elevated risk that should be fixed soon but is not an outage.",
	"high":     "High impact: significant degradation or a likely outage if left unfixed; needs prompt attention.",
	"critical": "Critical impact: an active outage, data risk or security exposure; needs immediate attention.",
}

const footer = "Generated by k8s-mcp from read-only cluster observations; verify before acting."

var (
	scriptRe = regexp.MustCompile(`(?is)<script.*?(</script\s*>|$)`)
	tagRe    = regexp.MustCompile(`</?[A-Za-z!][^>]*>`)
	lineLead = regexp.MustCompile(`(?i)^(\s*)([#*\-+=]|\d+\.|h[1-6]\.)`)
	footerRe = regexp.MustCompile(`(?i)generated by k8s-mcp`)
	jiraRe   = regexp.MustCompile(`(?i)^(\s*)(\{(code|panel|noformat|quote|color|html|include|anchor|section|column)\b|\\\{(code|panel|noformat|quote|color|html|include|anchor|section|column)\b|h[1-6]\.)`)
	nonLabel = regexp.MustCompile(`[^a-z0-9]+`)
	zeros    = strings.Repeat("0", 32)
	kvRe     = regexp.MustCompile(`([A-Za-z][A-Za-z0-9_.\-]*)(["']?\s*[:=]\s*["']?)((?:(?:Bearer|Basic|Token)\s+)?[^\s,;"'}&]+)`)
	specials = strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`, "{", `\{`, "}", `\}`, "!", `\!`, "|", `\|`, "~", `\~`, "<", `\<`, ">", `\>`)
)

// cleaner collects warnings, each once, in order.
type cleaner struct {
	warnings []string
	seen     map[string]bool
}

func (c *cleaner) warn(format string, a ...any) {
	m := fmt.Sprintf(format, a...)
	if c.seen == nil {
		c.seen = map[string]bool{}
	}
	if !c.seen[m] {
		c.seen[m] = true
		c.warnings = append(c.warnings, m)
	}
}

// maskLine masks credentials in one line: the value of every key[:=]value
// pair whose key name looks like a credential (so "password: x",
// "\"token\": \"x\"" and "--api-key=x" are caught), then the whole line when
// it still has a credential shape.
func maskLine(l string) string {
	l = kvRe.ReplaceAllStringFunc(l, func(m string) string {
		sub := kvRe.FindStringSubmatch(m)
		if redact.EnvValue(sub[1], sub[3]) == redact.Redacted {
			return sub[1] + sub[2] + redact.Redacted
		}
		return m
	})
	return redact.EnvValue("", l)
}

// maskLines masks whole private key blocks first (per-line masking alone
// would hide only the BEGIN line and keep the key body), then every line.
func maskLines(s string) string {
	s, _ = redact.MaskPrivateKeyBlocks(s)
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = maskLine(l)
	}
	return strings.Join(lines, "\n")
}

// clean runs the pipeline on one field, in this order: Sanitize, strip
// HTML (only when strip), scrub URL credentials, Secret-manifest check
// (fail closed), per-line masking, escape envelope markers, and a final
// check that masking is a fixed point. Tags are stripped before masking so
// that stripping cannot reassemble a token that masking has already passed.
func (c *cleaner) clean(field, s string, strip bool) string {
	s = untrusted.Sanitize(s)
	if strip {
		s = scriptRe.ReplaceAllString(s, "")
		s = tagRe.ReplaceAllString(s, "")
	}
	if scrubbed := flux.ScrubURLs(s); scrubbed != s {
		c.warn("%s: URL credentials were scrubbed", field)
		s = scrubbed
	}
	if redact.LooksLikeSecretManifest(s) {
		c.warn("%s: looks like a Secret manifest and was replaced", field)
		return SecretReplacement
	}
	if m := maskLines(s); m != s {
		c.warn("%s: a credential was masked", field)
		s = m
	}
	s = untrusted.Escape(zeros, s)
	for i := 0; i < 3; i++ {
		m := maskLines(s)
		if m == s {
			break
		}
		c.warn("%s: a credential was masked", field)
		s = m
	}
	return s
}

// esc backslash-escapes the characters that are live in Markdown or Jira
// wiki markup, and the sequence "generated by k8s-mcp" so a field cannot
// forge the footer. Line starts are escaped too when lines is true.
func esc(s string) string {
	s = specials.Replace(s)
	s = footerRe.ReplaceAllString(s, `Generated by k8s\-mcp`)
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = lineLead.ReplaceAllString(l, `$1\$2`)
	}
	return strings.Join(lines, "\n")
}

// field cleans a free-text field outside quotes and returns the masked,
// unescaped text (cut to max runes) plus its escaped form.
func (c *cleaner) field(name, s string, multiline bool, max int) (raw, escaped string) {
	s = c.clean(name, s, true)
	if multiline {
		lines := strings.Split(strings.ReplaceAll(s, "`", "'"), "\n")
		for i, l := range lines {
			lines[i] = strings.TrimRight(l, " \t")
		}
		s = strings.TrimSpace(strings.Join(lines, "\n"))
	} else {
		s = strings.Join(strings.Fields(strings.ReplaceAll(s, "`", "'")), " ")
	}
	if max > 0 {
		var was bool
		if s, was = cut(s, max); was && name != "" {
			c.cutWarn(name, max)
		}
	}
	return s, esc(s)
}

func (c *cleaner) cutWarn(name string, max int) {
	switch name {
	case "title", "summary":
		c.warn("%s was cut to %d characters", name, max)
	}
}

// cut shortens s to at most n runes, ending with an ellipsis when cut.
func cut(s string, n int) (string, bool) {
	if utf8.RuneCountInString(s) <= n {
		return s, false
	}
	r := []rune(s)
	return string(r[:n-1]) + "…", true
}

func maxBackticks(s string) int {
	best, run := 0, 0
	for _, r := range s {
		if r == '`' {
			run++
			if run > best {
				best = run
			}
		} else {
			run = 0
		}
	}
	return best
}

// fence renders quote inside a fenced block longer than any backtick run in it.
func fence(quote string) string {
	n := maxBackticks(quote) + 1
	if n < 3 {
		n = 3
	}
	f := strings.Repeat("`", n)
	return f + "\n" + quote + "\n" + f
}

// Label turns s into a label: lowercase [a-z0-9-], no spaces, at most 63 chars.
func Label(s string) string {
	s = strings.Trim(nonLabel.ReplaceAllString(strings.ToLower(s), "-"), "-")
	if len(s) > maxLabel {
		s = strings.Trim(s[:maxLabel], "-")
	}
	return s
}

// Draft validates in and builds the draft.
func Draft(in In) (Out, error) {
	sev := strings.ToLower(strings.TrimSpace(in.Severity))
	if _, ok := impact[sev]; !ok {
		return Out{}, fmt.Errorf("severity must be one of low, medium, high, critical (got %q)", untrusted.Sanitize(in.Severity))
	}
	c := &cleaner{}
	_, title := c.field("title", in.Title, false, MaxTitle)
	if title == "" {
		return Out{}, fmt.Errorf("title must not be empty")
	}
	_, summary := c.field("summary", in.Summary, true, MaxSummary)
	if summary == "" {
		return Out{}, fmt.Errorf("summary must not be empty")
	}
	clusterRaw, cluster := c.field("cluster", in.Cluster, false, maxField)
	if cluster == "" {
		return Out{}, fmt.Errorf("cluster must not be empty")
	}
	_, ns := c.field("namespace", in.Namespace, false, maxField)
	_, obj := c.field("object", in.Object, false, maxField)

	where := cluster
	if ns != "" {
		where += "/" + ns
	}
	line := "[" + sev + "] " + where + ": " + title
	if utf8.RuneCountInString(line) > MaxSummaryLine {
		line, _ = cut(line, MaxSummaryLine)
		c.warn("summary line was cut to %d characters", MaxSummaryLine)
	}

	out := Out{Summary: line}
	var b strings.Builder
	b.WriteString("## Summary\n\n" + summary + "\n")
	if obj != "" {
		b.WriteString("\nObject: " + obj + "\n")
	}
	b.WriteString("\n## Impact\n\n" + impact[sev] + "\n")

	b.WriteString("\n## Evidence\n")
	ev := in.Evidence
	if len(ev) > MaxEvidence {
		out.DroppedEvidence = len(ev) - MaxEvidence
		ev = ev[:MaxEvidence]
		c.warn("only the first %d evidence items were kept; %d dropped", MaxEvidence, out.DroppedEvidence)
	}
	if len(ev) == 0 {
		b.WriteString("\nNo evidence provided.\n")
	}
	for i, e := range ev {
		_, ref := c.field(fmt.Sprintf("evidence[%d].ref", i), e.Ref, false, maxRef)
		if ref == "" {
			ref = "(no ref)"
		}
		b.WriteString("\n- " + ref + "\n")
		if strings.TrimSpace(e.Quote) == "" {
			continue
		}
		name := fmt.Sprintf("evidence[%d].quote", i)
		q := strings.TrimSpace(c.clean(name, e.Quote, false))
		var was bool
		if q, was = cut(q, MaxQuote); was {
			c.warn("%s was cut to %d characters", name, MaxQuote)
		}
		// Jira wiki markup ignores Markdown fences, so the quote body is
		// escaped as well.
		lines := strings.Split(footerRe.ReplaceAllString(specials.Replace(q), `Generated by k8s\-mcp`), "\n")
		for j, l := range lines {
			if jiraRe.MatchString(l) {
				lines[j] = `\` + strings.TrimLeft(l, " \t")
			}
		}
		b.WriteString("\n" + fence(strings.Join(lines, "\n")) + "\n")
	}

	b.WriteString("\n## Suggested next steps\n")
	next := in.SuggestedNext
	if len(next) > MaxNext {
		out.DroppedNext = len(next) - MaxNext
		next = next[:MaxNext]
		c.warn("only the first %d suggested steps were kept; %d dropped", MaxNext, out.DroppedNext)
	}
	n := 0
	for i, s := range next {
		_, t := c.field(fmt.Sprintf("suggestedNext[%d]", i), s, false, MaxNextLen)
		if t == "" {
			continue
		}
		b.WriteString("\n- " + t)
		n++
	}
	if n == 0 {
		b.WriteString("\nNo specific next steps suggested.")
	}
	b.WriteString("\n\n---\n" + footer + "\n")
	out.Description = b.String()

	// Labels come from the masked cluster name, never from the raw input.
	cl := Label(clusterRaw)
	if cl == "" {
		cl = "unknown"
	}
	out.Labels = []string{"k8s-mcp", Label("severity-" + sev), Label("cluster-" + cl)}
	out.Warnings = append([]string{}, c.warnings...)
	return out, nil
}
