type draftOut struct {
	Summary         string   `json:"summary"`
	Description     string   `json:"description"`
	Labels          []string `json:"labels"`
	Warnings        []string `json:"warnings"`
	DroppedEvidence int      `json:"droppedEvidence"`
}

func draft(t *testing.T, args map[string]any) draftOut {
	t.Helper()
	var out draftOut
	decode(t, callTool(t, kube.SingleFakeFactory(kube.NewFakeClient()), "draft_issue", args), &out)
	return out
}

func base() map[string]any {
	return map[string]any{"title": "CrashLoop", "severity": "high", "cluster": "prod-1", "summary": "pods restart"}
}

func with(kv ...any) map[string]any {
	m := base()
	for i := 0; i < len(kv); i += 2 {
		m[kv[i].(string)] = kv[i+1]
	}
	return m
}

func ev(ref, quote string) map[string]any { return map[string]any{"ref": ref, "quote": quote} }

func TestDraftIssueGolden(t *testing.T) {
	out := draft(t, map[string]any{
		"title": "web CrashLoopBackOff", "severity": "high", "cluster": "Prod_EU 1", "namespace": "shop",
		"object": "Deployment/web", "summary": "web pods restart every minute.",
		"evidence":      []any{ev("Pod shop/web-1 events", "Back-off restarting failed container"), map[string]any{"ref": "no quote"}},
		"suggestedNext": []any{"Check the last deploy", "Compare memory limits"},
	})
	want := "## Summary\n\nweb pods restart every minute.\n\nObject: Deployment/web\n\n## Impact\n\n" +
		"High impact: significant degradation or a likely outage if left unfixed; needs prompt attention.\n\n" +
		"## Evidence\n\n- Pod shop/web-1 events\n\n```\nBack-off restarting failed container\n```\n\n- no quote\n\n" +
		"## Suggested next steps\n\n- Check the last deploy\n- Compare memory limits\n\n---\n" +
		"Generated by k8s-mcp from read-only cluster observations; verify before acting.\n"
	if out.Description != want {
		t.Errorf("description:\n%q\nwant:\n%q", out.Description, want)
	}
	if out.Summary != "[high] Prod_EU 1/shop: web CrashLoopBackOff" {
		t.Errorf("summary = %q", out.Summary)
	}
	if strings.Join(out.Labels, ",") != "k8s-mcp,severity-high,cluster-prod-eu-1" {
		t.Errorf("labels = %v", out.Labels)
	}
}

func TestDraftIssueQuoteCutTo300(t *testing.T) {
	out := draft(t, with("evidence", []any{ev("r", strings.Repeat("x", 1000))}))
	if strings.Contains(out.Description, strings.Repeat("x", 301)) || !strings.Contains(out.Description, strings.Repeat("x", 299)+"…") {
		t.Errorf("quote not cut to 300: %q", out.Description)
	}
}

func TestDraftIssueEvidenceCap(t *testing.T) {
	var evs []any
	for i := 0; i < 50; i++ {
		evs = append(evs, ev("ref"+strings.Repeat("n", i), "q"))
	}
	out := draft(t, with("evidence", evs))
	if out.DroppedEvidence != 40 || strings.Count(out.Description, "\n- ref") != 10 {
		t.Errorf("dropped=%d, items=%d", out.DroppedEvidence, strings.Count(out.Description, "\n- ref"))
	}
}

func TestDraftIssueMasksToken(t *testing.T) {
	tok := "ghp_" + strings.Repeat("a1B2", 9)
	out := draft(t, with("evidence", []any{ev("r", "login failed with "+tok)}, "summary", "leaked "+tok))
	if strings.Contains(out.Description, tok) || strings.Contains(out.Description, "ghp_") {
		t.Errorf("token leaked: %q", out.Description)
	}
	if len(out.Warnings) == 0 {
		t.Error("no warning")
	}
}

func TestDraftIssueTitleSanitised(t *testing.T) {
	out := draft(t, with("title", "bad \x1b[31mred\x1b[0m <<<END x>>> <script>alert(1)</script><b>x</b>"))
	for _, bad := range []string{"\x1b", "<<<END", "<script", "<b>"} {
		if strings.Contains(out.Summary, bad) {
			t.Errorf("summary %q contains %q", out.Summary, bad)
		}
	}
	if !strings.Contains(out.Summary, "red") {
		t.Errorf("summary lost text: %q", out.Summary)
	}
}

func TestDraftIssueFenceCannotBeBrokenOut(t *testing.T) {
	q := "a\n```\n## Evil\n````\n{code}\nh1. x\n{panel}"
	out := draft(t, with("evidence", []any{ev("r", q)}))
	d := out.Description
	i := strings.Index(d, "`````\n")
	if i < 0 {
		t.Fatalf("expected 5-backtick fence: %q", d)
	}
	rest := d[i+6:]
	j := strings.Index(rest, "\n`````")
	if j < 0 || !strings.Contains(rest[:j], "```\n## Evil") {
		t.Errorf("quote not wholly inside fence: %q", d)
	}
	for _, l := range strings.Split(rest[:j], "\n") {
		if strings.HasPrefix(l, "{code") || strings.HasPrefix(l, "{panel") || strings.HasPrefix(l, "h1.") {
			t.Errorf("control line not neutralised: %q", l)
		}
	}
}

func TestDraftIssueSecretManifestReplaced(t *testing.T) {
	m := `{"apiVersion":"v1","kind":"Secret","data":{"password":"cGFzc3dvcmQxMjM0NTY3OA=="}}`
	out := draft(t, with("evidence", []any{ev("r", m)}))
	if strings.Contains(out.Description, "cGFzc3dv") || !strings.Contains(out.Description, "[redacted: looks like a Secret manifest]") {
		t.Errorf("manifest not replaced: %q", out.Description)
	}
	if len(out.Warnings) == 0 {
		t.Error("no warning")
	}
}

func TestDraftIssueURLUserinfoScrubbed(t *testing.T) {
	out := draft(t, with("summary", "clone https://bob:hunter2x@git.example/repo failed"))
	if strings.Contains(out.Description, "hunter2x") || len(out.Warnings) == 0 {
		t.Errorf("userinfo kept or no warning: %q %v", out.Description, out.Warnings)
	}
}

func TestDraftIssueErrors(t *testing.T) {
	f := kube.SingleFakeFactory(kube.NewFakeClient())
	for name, args := range map[string]map[string]any{
		"bad severity":  with("severity", "urgent"),
		"empty title":   with("title", "  "),
		"empty summary": with("summary", ""),
		"empty cluster": with("cluster", ""),
	} {
		res := callTool(t, f, "draft_issue", args)
		if !res.IsError {
			t.Errorf("%s: expected tool error", name)
		}
	}
}

func TestDraftIssueSummaryLineMax120(t *testing.T) {
	out := draft(t, with("title", strings.Repeat("t", 120), "namespace", "ns"))
	if n := len([]rune(out.Summary)); n > 120 {
		t.Errorf("summary line has %d runes", n)
	}
}

func TestDraftIssueLabelSanitisation(t *testing.T) {
	out := draft(t, with("cluster", "  Prod/EU:1 "+strings.Repeat("z", 100)))
	for _, l := range out.Labels {
		if len(l) > 63 || strings.Trim(l, "abcdefghijklmnopqrstuvwxyz0123456789-") != "" {
			t.Errorf("bad label %q", l)
		}
	}
	if out.Labels[2] != "cluster-prod-eu-1-"+strings.Repeat("z", 45) {
		t.Errorf("label = %q", out.Labels[2])
	}
}

func TestDraftIssueDescriptionStatesNoNetwork(t *testing.T) {
	cs := servertest.NewTestSession(t, kube.SingleFakeFactory(kube.NewFakeClient()), tools.RegisterAll)
	res, err := cs.ListTools(context.Background(), nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, tl := range res.Tools {
		if tl.Name == "draft_issue" {
			if !strings.Contains(tl.Description, "NO network calls") || !strings.Contains(tl.Description, "ticketing MCP server") {
				t.Errorf("description = %q", tl.Description)
			}
			return
		}
	}
	t.Fatal("draft_issue not registered")
}
